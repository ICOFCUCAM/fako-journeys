#!/usr/bin/env node
/* Write the published journey requirements. Section C phase C3.
 *
 *     node tools/journey-requirements.js            # what it would write
 *     node tools/journey-requirements.js --fetch    # write it
 *
 * C7's table, generated from the rate card the site already publishes rather
 * than typed, so the two denominations of the same journey cannot drift apart.
 * Every row carries the rate card's version hash, which is what makes C8's
 * "original target vs current requirement" answerable rather than merely
 * observable.
 */
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..");
const J = require("../scripts/journey-catalogue.js");

const html = fs.readFileSync(path.join(ROOT, "journey-fund.html"), "utf-8");
const m = html.match(/id="jf-data">([\s\S]*?)<\/script>/);
if (!m) { console.log("no jf-data on the fund page — nothing to derive from"); process.exit(1); }
const D = JSON.parse(m[1]);

const rows = J.catalogue(D);
const out = {
  $comment: "Generated by tools/journey-requirements.js from the rate card on " +
            "journey-fund.html. Do not edit by hand — C7 requires that a " +
            "journey's point requirement be derived from its service pricing, " +
            "and a hand edit is how the two denominations start disagreeing.",
  programId: J.DRAFT_PROGRAM,
  rateCardVersion: D.v || "unknown",
  journeys: rows,
};

const file = path.join(ROOT, "data", "journey-requirements.json");
const body = JSON.stringify(out, null, 1) + "\n";
const before = fs.existsSync(file) ? fs.readFileSync(file, "utf-8") : "";

console.log("journey requirements: %d journey(s) at rate card %s",
            rows.length, out.rateCardVersion);
const band = rows.filter((r) => r.band);
console.log("  %d country journeys at the default shape, %d priced routes",
            rows.length - band.length, band.length);
if (body === before) { console.log("  unchanged"); process.exit(0); }
if (!process.argv.includes("--fetch")) {
  console.log("  dry run — add --fetch to write data/journey-requirements.json");
  process.exit(0);
}
fs.writeFileSync(file, body);
console.log("  wrote data/journey-requirements.json");
